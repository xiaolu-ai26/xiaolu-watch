#!/usr/bin/env python3
"""Start one component in the foreground, appending its output to data/logs/<name>.log.

Used by launchd (macOS) and Task Scheduler (Windows) entries generated by setup.py:

    python3 scripts/service.py receiver   # sealed v2 receiver on 127.0.0.1:18437
    python3 scripts/service.py ingress    # loopback HTTPS upstream on 127.0.0.1:18438 (+ pairing claim)
    python3 scripts/service.py pipeline   # local ASR -> Markdown (-> optional Feishu)
    python3 scripts/service.py sync       # Mac only: pull notes from a Windows receiver once

Add --foreground to print to the terminal instead of the log file.
"""
import argparse
import json
import os
from pathlib import Path
import runpy
import sys

REPO = Path(__file__).resolve().parent.parent


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('component', choices=['receiver', 'ingress', 'pipeline', 'sync'])
    p.add_argument('--home', type=Path, default=Path(os.environ.get('XIAOLU_WATCH_HOME') or REPO / 'data'))
    p.add_argument('--foreground', action='store_true')
    a = p.parse_args()
    home = a.home.resolve()
    settings = json.loads((home / 'settings.json').read_text(encoding='utf-8'))
    receiver_root = settings.get('receiver', {}).get('root') or str(home / 'receiver')
    ingress_port = str(settings.get('ingress', {}).get('port', 18438))
    receiver_port = str(settings.get('receiver', {}).get('port', 18437))
    commands = {
        'receiver': [REPO / 'receiver' / 'receiver.py', 'serve', '--root', receiver_root],
        'ingress': [REPO / 'receiver' / 'https_ingress.py', '--port', ingress_port, '--upstream-port', receiver_port,
                    '--bootstrap-root', receiver_root],
        'pipeline': [REPO / 'processor' / 'pipeline.py', '--home', str(home)],
        'sync': [REPO / 'processor' / 'sync_notes.py', '--home', str(home)],
    }
    script, *args = commands[a.component]
    os.environ.update(PYTHONUTF8='1', PYTHONIOENCODING='utf-8', PYTHONUNBUFFERED='1')
    if settings.get('ffmpeg_dir'):
        os.environ['PATH'] = settings['ffmpeg_dir'] + os.pathsep + os.environ.get('PATH', '')
    if not a.foreground:
        logs = home / 'logs'
        logs.mkdir(parents=True, exist_ok=True)
        log = open(logs / f'{a.component}.log', 'a', encoding='utf-8', buffering=1)
        os.dup2(log.fileno(), 1)
        os.dup2(log.fileno(), 2)
        sys.stdout = sys.stderr = log
    # Run in this same process (no child): stopping the service stops the component.
    os.chdir(REPO)
    sys.path.insert(0, str(script.parent))
    sys.argv = [str(script), *args]
    runpy.run_path(str(script), run_name='__main__')


if __name__ == '__main__':
    main()
